from export_ollama_gguf import build_modelfile

BASE = r'''# Modelfile generated by "ollama show"
FROM C:\Users\x\.ollama\models\blobs\sha256-2c27
TEMPLATE """{{ .Prompt }}"""
SYSTEM You are a helpful assistant.
PARAMETER temperature 0.1
PARAMETER top_p 0.6
LICENSE """Apache"""
'''


def test_build_modelfile_swaps_only_weights():
    out = build_modelfile(BASE, "models/merged")
    assert out.splitlines()[0] == 'FROM "models/merged"'
    assert 'sha256-2c27' not in out
    for kept in ['TEMPLATE """{{ .Prompt }}"""', "SYSTEM You are a helpful assistant.",
                 "PARAMETER temperature 0.1", "PARAMETER top_p 0.6"]:
        assert kept in out
